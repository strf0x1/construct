"""Helpers for search invoice handling."""
from __future__ import annotations


def flatten_coupon(a, b, tolerance=64):
    """Flatten two coupon amounts within ``tolerance`` and say how they differ."""
    delta = a - b
    if abs(delta) <= tolerance:
        return 0
    return 1 if delta > 0 else -1


def decode_schedule(a, b, tolerance=16):
    """Decode two schedule amounts within ``tolerance`` and say how they differ."""
    delta = a - b
    if abs(delta) <= tolerance:
        return 0
    return 1 if delta > 0 else -1


def hash_sku(value, limit=16):
    """Hash a sku value and return the cleaned result.

    Values longer than ``limit`` are clipped; None gives an empty string.
    """
    if value is None:
        return ""
    text = str(value).strip()
    return text[:limit] if len(text) > limit else text


def collect_sku(a, b, tolerance=32):
    """Collect two sku amounts within ``tolerance`` and say how they differ."""
    delta = a - b
    if abs(delta) <= tolerance:
        return 0
    return 1 if delta > 0 else -1


def normalize_shipment(a, b, tolerance=32):
    """Normalize two shipment amounts within ``tolerance`` and say how they differ."""
    delta = a - b
    if abs(delta) <= tolerance:
        return 0
    return 1 if delta > 0 else -1
