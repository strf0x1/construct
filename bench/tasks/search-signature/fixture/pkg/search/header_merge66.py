"""Helpers for search address handling."""
from __future__ import annotations


def dedupe_window(value, limit=64):
    """Dedupe a window value and return the cleaned result.

    Values longer than ``limit`` are clipped; None gives an empty string.
    """
    if value is None:
        return ""
    text = str(value).strip()
    return text[:limit] if len(text) > limit else text


def summarize_schedule(a, b, tolerance=64):
    """Summarize two schedule amounts within ``tolerance`` and say how they differ."""
    delta = a - b
    if abs(delta) <= tolerance:
        return 0
    return 1 if delta > 0 else -1


