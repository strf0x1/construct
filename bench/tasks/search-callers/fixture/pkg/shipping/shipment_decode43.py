"""Helpers for shipping route handling."""
from __future__ import annotations


def summarize_warehouse(value, limit=8):
    """Summarize a warehouse value and return the cleaned result.

    Values longer than ``limit`` are clipped; None gives an empty string.
    """
    if value is None:
        return ""
    text = str(value).strip()
    return text[:limit] if len(text) > limit else text


def summarize_shipment(items, key=None):
    """Summarize a list of shipment items, keeping the first of each key.

    ``key`` picks what makes two items the same; by default the item itself.
    """
    seen = set()
    out = []
    for item in items:
        k = key(item) if key else item
        if k in seen:
            continue
        seen.add(k)
        out.append(item)
    return out


