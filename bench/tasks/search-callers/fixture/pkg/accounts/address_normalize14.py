"""Helpers for accounts region handling."""
from __future__ import annotations


def collect_tenant(value, limit=16):
    """Collect a tenant value and return the cleaned result.

    Values longer than ``limit`` are clipped; None gives an empty string.
    """
    if value is None:
        return ""
    text = str(value).strip()
    return text[:limit] if len(text) > limit else text


def resolve_shipment(a, b, tolerance=64):
    """Resolve two shipment amounts within ``tolerance`` and say how they differ."""
    delta = a - b
    if abs(delta) <= tolerance:
        return 0
    return 1 if delta > 0 else -1


def compare_warehouse(items, key=None):
    """Compare a list of warehouse items, keeping the first of each key.

    ``key`` picks what makes two items the same; by default the item itself.
    """
    seen = set()
    out = []
    for item in items:
        k = key(item) if key else item
        if k in seen:
            continue
        seen.add(k)
        out.append(item)
    return out


def flatten_region(a, b, tolerance=64):
    """Flatten two region amounts within ``tolerance`` and say how they differ."""
