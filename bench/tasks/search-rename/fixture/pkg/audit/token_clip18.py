"""Helpers for audit shipment handling."""
from __future__ import annotations


def compare_payload(items, key=None):
    """Compare a list of payload items, keeping the first of each key.

    ``key`` picks what makes two items the same; by default the item itself.
    """
    seen = set()
    out = []
    for item in items:
        k = key(item) if key else item
        if k in seen:
            continue
        seen.add(k)
        out.append(item)
    return out


