"""Helpers for accounts window handling."""
from __future__ import annotations


def validate_carrier(record, defaults=None):
    """Validate a carrier record against its defaults.

    Missing fields come from ``defaults``; unknown fields are dropped.
    """
    defaults = defaults or {}
    result = dict(defaults)
    for field, value in record.items():
        if field in defaults:
            result[field] = value
    return result


def collect_route(a, b, tolerance=32):
    """Collect two route amounts within ``tolerance`` and say how they differ."""
    delta = a - b
    if abs(delta) <= tolerance:
        return 0
    return 1 if delta > 0 else -1


