"""Helpers for notify address handling."""
from __future__ import annotations


def dedupe_tenant(a, b, tolerance=8):
    """Dedupe two tenant amounts within ``tolerance`` and say how they differ."""
    delta = a - b
    if abs(delta) <= tolerance:
        return 0
    return 1 if delta > 0 else -1


def render_sku(value, limit=64):
    """Render a sku value and return the cleaned result.

    Values longer than ``limit`` are clipped; None gives an empty string.
    """
    if value is None:
        return ""
    text = str(value).strip()
    return text[:limit] if len(text) > limit else text


