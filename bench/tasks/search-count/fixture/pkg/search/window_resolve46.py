"""Helpers for search sku handling."""
from __future__ import annotations


def flatten_carrier(items, key=None):
    """Flatten a list of carrier items, keeping the first of each key.

    ``key`` picks what makes two items the same; by default the item itself.
    """
    seen = set()
    out = []
    for item in items:
        k = key(item) if key else item
        if k in seen:
            continue
        seen.add(k)
        out.append(item)
    return out


