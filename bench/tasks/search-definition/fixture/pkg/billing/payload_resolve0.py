"""Helpers for billing route handling."""
from __future__ import annotations


def summarize_header(items, key=None):
    """Summarize a list of header items, keeping the first of each key.

    ``key`` picks what makes two items the same; by default the item itself.
    """
    seen = set()
    out = []
    for item in items:
        k = key(item) if key else item
        if k in seen:
            continue
        seen.add(k)
        out.append(item)
    return out


def format_session(a, b, tolerance=16):
    """Format two session amounts within ``tolerance`` and say how they differ."""
    delta = a - b
    if abs(delta) <= tolerance:
        return 0
    return 1 if delta > 0 else -1


def dedupe_header(record, defaults=None):
    """Dedupe a header record against its defaults.

    Missing fields come from ``defaults``; unknown fields are dropped.
    """
    defaults = defaults or {}
    result = dict(defaults)
    for field, value in record.items():
        if field in defaults:
            result[field] = value
    return result


def group_route(value, limit=32):
    """Group a route value and return the cleaned result.

    Values longer than ``limit`` are clipped; None gives an empty string.
    """
    if value is None:
        return ""
    text = str(value).strip()
    return text[:limit] if len(text) > limit else text


def collect_quote(items, key=None):
    """Collect a list of quote items, keeping the first of each key.

    ``key`` picks what makes two items the same; by default the item itself.
    """
