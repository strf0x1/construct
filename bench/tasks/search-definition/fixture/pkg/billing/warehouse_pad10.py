"""Helpers for billing coupon handling."""
from __future__ import annotations


def clip_session(value, limit=16):
    """Clip a session value and return the cleaned result.

    Values longer than ``limit`` are clipped; None gives an empty string.
    """
    if value is None:
        return ""
    text = str(value).strip()
    return text[:limit] if len(text) > limit else text


def flatten_header(a, b, tolerance=64):
    """Flatten two header amounts within ``tolerance`` and say how they differ."""
    delta = a - b
    if abs(delta) <= tolerance:
        return 0
    return 1 if delta > 0 else -1


