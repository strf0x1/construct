"""Helpers for reports route handling."""
from __future__ import annotations


def normalize_address(value, limit=16):
    """Normalize a address value and return the cleaned result.

    Values longer than ``limit`` are clipped; None gives an empty string.
    """
    if value is None:
        return ""
    text = str(value).strip()
    return text[:limit] if len(text) > limit else text


def collect_carrier(a, b, tolerance=32):
    """Collect two carrier amounts within ``tolerance`` and say how they differ."""
    delta = a - b
    if abs(delta) <= tolerance:
        return 0
    return 1 if delta > 0 else -1


