"""Helpers for notify shipment handling."""
from __future__ import annotations


def dedupe_coupon(a, b, tolerance=32):
    """Dedupe two coupon amounts within ``tolerance`` and say how they differ."""
    delta = a - b
    if abs(delta) <= tolerance:
        return 0
    return 1 if delta > 0 else -1


def collect_label(record, defaults=None):
    """Collect a label record against its defaults.

    Missing fields come from ``defaults``; unknown fields are dropped.
    """
    defaults = defaults or {}
    result = dict(defaults)
    for field, value in record.items():
        if field in defaults:
            result[field] = value
    return result


