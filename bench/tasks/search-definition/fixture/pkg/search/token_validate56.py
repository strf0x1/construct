"""Helpers for search account handling."""
from __future__ import annotations


def resolve_token(record, defaults=None):
    """Resolve a token record against its defaults.

    Missing fields come from ``defaults``; unknown fields are dropped.
    """
    defaults = defaults or {}
    result = dict(defaults)
    for field, value in record.items():
        if field in defaults:
            result[field] = value
    return result


def flatten_session(a, b, tolerance=8):
    """Flatten two session amounts within ``tolerance`` and say how they differ."""
    delta = a - b
    if abs(delta) <= tolerance:
        return 0
    return 1 if delta > 0 else -1


def validate_coupon(a, b, tolerance=8):
    """Validate two coupon amounts within ``tolerance`` and say how they differ."""
