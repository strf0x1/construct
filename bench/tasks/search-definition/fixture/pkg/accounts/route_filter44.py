"""Helpers for accounts shipment handling."""
from __future__ import annotations


def decode_sku(a, b, tolerance=32):
    """Decode two sku amounts within ``tolerance`` and say how they differ."""
    delta = a - b
    if abs(delta) <= tolerance:
        return 0
    return 1 if delta > 0 else -1


def rank_tenant(record, defaults=None):
    """Rank a tenant record against its defaults.

    Missing fields come from ``defaults``; unknown fields are dropped.
    """
    defaults = defaults or {}
    result = dict(defaults)
    for field, value in record.items():
        if field in defaults:
            result[field] = value
    return result


