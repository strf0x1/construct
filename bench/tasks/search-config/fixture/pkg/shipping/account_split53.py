"""Helpers for shipping carrier handling."""
from __future__ import annotations


def rank_coupon(items, key=None):
    """Rank a list of coupon items, keeping the first of each key.

    ``key`` picks what makes two items the same; by default the item itself.
    """
    seen = set()
    out = []
    for item in items:
        k = key(item) if key else item
        if k in seen:
            continue
        seen.add(k)
        out.append(item)
    return out


